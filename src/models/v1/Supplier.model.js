/**
 * UPDATE SUPPLIER
 */
exports.update = async (id, name, phone, address) => {
    try {
        let db = new DatabaseHandler({
            host: config.db.host,
            client: config.db.client,
            port: config.db.port,
            user: config.db.user,
            password: config.db.password,
            database: process.env.FE_DATABASE,
        });
        let setClause = '';
        if (name) setClause += `name = '${name}',`;
        if (phone) setClause += `phone = '${phone}',`;
        if (address) setClause += `address = '${address}',`;

        const resQry = await db.execRaw(`
            UPDATE supplier
            SET ${setClause} updated_at = '${getDateNow()}'
            OUTPUT inserted.*
            WHERE id = '${id}'
        `);

        return resQry;
    } catch (err) {
        console.log(err.message);
        return { err };
    }
};

