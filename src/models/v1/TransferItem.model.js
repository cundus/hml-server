"use strict";

const crypto = require("crypto");
const { DatabaseHandler } = require("../plugins/dbHandler.plugin");
const { getDateNow } = require("../../utils/Helpers");
const config = require("../../config/config");



/**
 * LIST TRANSFER ITEMS
 */
exports.list = async (Page, RowsPerPage) => {
    try {
        let db = new DatabaseHandler({
            host: config.db.host,
            client: config.db.client,
            port: config.db.port,
            user: config.db.user,
            password: config.db.password,
            database: process.env.FE_DATABASE,
        }); let offset = 0;

        if (Page != 0) offset = (Page - 1) * RowsPerPage;

        const resQry = await db.execRaw(`
            SELECT *
             FROM  transfer_item  
            ORDER BY created_at DESC
            ${Page != 0 ? `OFFSET ${offset} ROWS FETCH NEXT ${RowsPerPage} ROWS ONLY` : ""}
        `);

        const [total] = await db.execRaw(`
            SELECT COUNT(1) AS Total
             FROM  transfer_item  
        `);

        return {
            results: resQry,
            pagination: {
                TotalData: parseInt(total.total),
                TotalPage: Math.ceil(parseInt(total.total) / RowsPerPage),
                TotalPerPage: RowsPerPage,
            },
        };
    } catch (err) {
        console.log(err.message);
        return { err };
    }
};

/**
 * CREATE TRANSFER ITEM
 */
exports.create = async (transfer_request_id, product_id, qty, unit) => {
    try {
        let db = new DatabaseHandler({
            host: config.db.host,
            client: config.db.client,
            port: config.db.port,
            user: config.db.user,
            password: config.db.password,
            database: process.env.FE_DATABASE,
        });
        const id = crypto.randomUUID();

        // Cek ID random jika bentrok
        const checkId = await db.execRaw(`
            SELECT *
             FROM  transfer_item  
            WHERE id = '${id}'
        `);

        if (checkId.length > 0) {
            return { results: [] };
        }

        let columns = ['id'];
        let values = [`'${id}'`];

        if (transfer_request_id) { columns.push('transfer_request_id'); values.push(`'${transfer_request_id}'`); }
        if (product_id) { columns.push('product_id'); values.push(`'${product_id}'`); }
        if (qty !== undefined) { columns.push('qty'); values.push(`${qty}`); }
        if (unit) { columns.push('unit'); values.push(`'${unit}'`); }

        columns.push('created_at');
        values.push(`'${getDateNow()}'`);

        columns.push('updated_at');
        values.push(`'${getDateNow()}'`);

        const resQry = await db.execRaw(`
            INSERT INTO transfer_item (${columns.join(', ')})
            OUTPUT inserted.*
            VALUES (${values.join(', ')})
        `);

        return resQry;
    } catch (err) {
        console.log(err.message);
        return { err };
    }
};

